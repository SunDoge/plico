using System;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Plico.Generators;

[Generator(LanguageNames.CSharp)]
public sealed class ComponentGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor Unsupported = new("PLICO001", "Unsupported component",
        "Cannot generate component '{0}': {1}", "Plico", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor Collision = new("PLICO002", "Component name collision",
        "Component wrapper '{0}' conflicts with an existing member", "Plico", DiagnosticSeverity.Error, true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var methods = context.SyntaxProvider.ForAttributeWithMetadataName("Plico.ComponentAttribute",
            static (node, _) => node is MethodDeclarationSyntax,
            static (ctx, _) => (IMethodSymbol)ctx.TargetSymbol);
        var enabled = context.AnalyzerConfigOptionsProvider.Select(static (options, _) =>
            options.GlobalOptions.TryGetValue("build_property.PlicoComponentInterceptors", out var value) && string.Equals(value, "true", StringComparison.OrdinalIgnoreCase));
        context.RegisterSourceOutput(methods.Combine(enabled), static (ctx, pair) => { if (!pair.Right) Generate(ctx, pair.Left); });
    }
    private static void Generate(SourceProductionContext context, IMethodSymbol method)
    {
        var syntax = (MethodDeclarationSyntax)method.DeclaringSyntaxReferences[0].GetSyntax(context.CancellationToken);
        var type = method.ContainingType;
        string? reason = null;
        if (!method.Name.EndsWith("Body", StringComparison.Ordinal) || method.Name.Length == 4)
            reason = "the method name must end with Body (CounterBody generates Counter)";
        else if (!method.ReturnsVoid || method.IsAsync || method.IsExtensionMethod || method.IsGenericMethod || method.IsAbstract || method.IsExtern
            || method.PartialDefinitionPart is not null || method.PartialImplementationPart is not null || syntax.Body is null && syntax.ExpressionBody is null)
            reason = "use a synchronous, non-generic void method with a body";
        else if (type.ContainingType is not null || type.IsGenericType || type.TypeKind != TypeKind.Class || type.IsRecord
            || type.DeclaringSyntaxReferences.Any(r => r.GetSyntax(context.CancellationToken) is not ClassDeclarationSyntax c
                || !c.Modifiers.Any(SyntaxKind.PartialKeyword)))
            reason = "the containing type must be a top-level, non-generic partial class";
        else if (method.Parameters.Length == 0 || method.Parameters[0].Type.ToDisplayString() != "Plico.Ui" || method.Parameters[0].RefKind != RefKind.None)
            reason = "the first parameter must be a Plico.Ui passed by value";
        else if (method.Parameters.Any(p => p.IsParams || p.Name.StartsWith("__plico", StringComparison.Ordinal)
            || p.IsOptional && !p.HasExplicitDefaultValue || p.Type.TypeKind == TypeKind.Pointer || p.Type.TypeKind == TypeKind.FunctionPointer))
            reason = "params, pointer and reserved __plico parameters are unsupported";
        if (reason is not null)
        {
            context.ReportDiagnostic(Diagnostic.Create(Unsupported, syntax.Identifier.GetLocation(), method.Name, reason)); return;
        }
        string name = method.Name.Substring(0, method.Name.Length - 4);
        if (type.GetMembers(name).Any())
        {
            context.ReportDiagnostic(Diagnostic.Create(Collision, syntax.Identifier.GetLocation(), name)); return;
        }
        ulong hash = 14695981039346656037UL;
        foreach (char c in method.ContainingAssembly.Identity.Name + "|" + type.ToDisplayString() + "|" + method.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat))
            hash = unchecked((hash ^ c) * 1099511628211UL);
        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        bool hasNamespace = !type.ContainingNamespace.IsGlobalNamespace;
        if (hasNamespace) source.Append("namespace ").Append(type.ContainingNamespace.ToDisplayString()).Append(" {\n");
        source.Append(Access(type.DeclaredAccessibility)).Append(type.IsStatic ? " static" : "").Append(" partial class @").Append(type.Name).Append(" {\n");
        source.Append("    ").Append(Access(method.DeclaredAccessibility)).Append(method.IsStatic ? " static" : "").Append(" void @").Append(name).Append('(');
        source.Append(string.Join(", ", method.Parameters.Select(Parameter)));
        source.Append(", [global::System.Runtime.CompilerServices.CallerFilePathAttribute] string __plicoFile = \"\", ")
            .Append("[global::System.Runtime.CompilerServices.CallerLineNumberAttribute] int __plicoLine = 0) {\n")
            .Append("        using var __plicoScope = @").Append(method.Parameters[0].Name).Append(".Scope(file: __plicoFile, line: __plicoLine);\n")
            .Append("        using var __plicoComponent = @").Append(method.Parameters[0].Name).Append(".Scope(0x").Append(hash.ToString("x16", CultureInfo.InvariantCulture)).Append("UL);\n")
            .Append("        @").Append(method.Name).Append('(').Append(string.Join(", ", method.Parameters.Select(p => Ref(p.RefKind) + "@" + p.Name)))
            .Append(");\n    }\n}\n");
        if (hasNamespace) source.Append("}\n");
        context.AddSource(type.Name + "." + name + "." + hash.ToString("x16", CultureInfo.InvariantCulture) + ".g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
    }
    private static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat.WithMiscellaneousOptions(SymbolDisplayFormat.FullyQualifiedFormat.MiscellaneousOptions | SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);
    private static string Parameter(IParameterSymbol p) => Ref(p.RefKind) + p.Type.ToDisplayString(TypeFormat)
        + " @" + p.Name + (p.HasExplicitDefaultValue ? " = " + Default(p) : "");
    private static string Default(IParameterSymbol p)
    {
        object? value = p.ExplicitDefaultValue;
        if (value is null) return "default";
        if (p.Type.TypeKind == TypeKind.Enum) return "(" + p.Type.ToDisplayString(TypeFormat) + ")" + Convert.ToString(value, CultureInfo.InvariantCulture);
        if (value is string s) return SymbolDisplay.FormatLiteral(s, true);
        if (value is char c) return SymbolDisplay.FormatLiteral(c, true);
        if (value is bool b) return b ? "true" : "false";
        if (value is double d && (double.IsNaN(d) || double.IsInfinity(d))) return "global::System.Double." + (double.IsNaN(d) ? "NaN" : d > 0 ? "PositiveInfinity" : "NegativeInfinity");
        if (value is float f && (float.IsNaN(f) || float.IsInfinity(f))) return "global::System.Single." + (float.IsNaN(f) ? "NaN" : f > 0 ? "PositiveInfinity" : "NegativeInfinity");
        return Convert.ToString(value, CultureInfo.InvariantCulture) + (value is float ? "F" : value is double ? "D" : value is decimal ? "M" : value is ulong ? "UL" : value is long ? "L" : value is uint ? "U" : "");
    }
    private static string Ref(RefKind kind) => kind == RefKind.Ref ? "ref " : kind == RefKind.Out ? "out " : kind == RefKind.In || kind == RefKind.RefReadOnlyParameter ? "in " : "";
    private static string Access(Accessibility access) => access == Accessibility.Public ? "public" : access == Accessibility.Private ? "private"
        : access == Accessibility.Protected ? "protected" : access == Accessibility.ProtectedOrInternal ? "protected internal"
        : access == Accessibility.ProtectedAndInternal ? "private protected" : "internal";
}
